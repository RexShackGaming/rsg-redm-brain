"""Build data/rdr3_discoveries/MAP.md: an index of every file in the femga rdr3_discoveries mirror.
Usage: python3 tools/map_discoveries.py <brain_dir>
"""
import os, re, sys
from collections import defaultdict

BRAIN = sys.argv[1]
ROOT = os.path.join(BRAIN, 'data', 'rdr3_discoveries')
OUT = os.path.join(ROOT, 'MAP.md')

def human(n):
    for u in ('B', 'KB', 'MB'):
        if n < 1024: return f'{n:.0f}{u}'
        n /= 1024
    return f'{n:.1f}GB'

def describe(path):
    """First markdown heading / comment, and first data-looking line."""
    title, sample = '', ''
    try:
        with open(path, encoding='utf-8', errors='ignore') as fh:
            for i, line in enumerate(fh):
                s = line.strip()
                if not s: continue
                if not title:
                    m = re.match(r'^(#+\s*|--+\s*|//\s*)(.+)', s)
                    if m and len(m.group(2)) > 3: title = m.group(2)[:90]
                if not sample and re.search(r'0x[0-9A-Fa-f]{6,}|["\'][\w]+["\']\s*[,=}]|^\|.*\|', s) and not s.startswith('|--') and not s.startswith('|:-'):
                    sample = s[:140]
                if (title and sample) or i > 400: break
    except Exception:
        pass
    return title.replace('|', '/'), sample.replace('|', '¦').replace('`', "'")

groups = defaultdict(list)
for d, dirs, files in os.walk(ROOT):
    dirs.sort()
    for f in sorted(files):
        if f in ('MAP.md', '.gitkeep'): continue
        p = os.path.join(d, f)
        rel = os.path.relpath(p, ROOT).replace('\\', '/')
        top = rel.split('/')[0] if '/' in rel else '(root)'
        with open(p, 'rb') as fh: lines = sum(1 for _ in fh)
        groups[top].append((rel, os.path.getsize(p), lines, *describe(p)))

HINTS = {
    'AI': 'Ped config/reset flags, combat styles, relationships, game EVENTS + data sizes, animal tuning, looting/carrying flags',
    'Controls': 'Control/input hashes (INPUT_*) for IsControlJustPressed, prompts',
    'Stats': 'Challenge stats only',
    'animations': 'Anim dicts + clip names, scenarios, kit emotes, anim events',
    'audio': 'Soundsets, frontend sounds, music events, audio banks',
    'boneNames': 'Ped/horse bone names and indexes',
    'clothes': 'Clothing hashes, metaped outfits, colour palettes, overlays',
    'databindings': 'UI databindings for HUD contexts (honor, trader, moonshine...) and UI apps',
    'discoveredNatives': 'Community-discovered natives with hashes and params',
    'doorHashes': 'Door hashes + coords (for doorlock)',
    'graphics': 'PTFX, markers, animpostfx, timecycles, explosions, HUD presets, prompt types, minimap/radar',
    'imaps': 'IMAP (map chunk) hashes with coords',
    'interiors': 'Interior ids, coords, entity sets',
    'objects': 'Prop/object model names, pickups, propsets, composites (plants/herbs), entity extensions',
    'peds': 'Ped model names (humans, animals, horses), MP peds',
    'peds_customization': 'Outfits, decals, wearable states, expressions',
    'tasks': 'Animal interaction, horse action and item interaction task data',
    'useful_info_from_rpfs': 'Blip styles + modifiers, colours, texture dictionaries (blip icons, inventory items, HUD, menus) for NUI/blips',
    'vehicles': 'Vehicle list (wagons, boats...), trains, liveries, tints, propsets, extras, bones',
    'weapons': 'Weapon hashes, ammo types, components',
    'weather': 'Weather types and variations',
    'zones': 'Map zone / district / town hashes (README)',
}

out = ['# rdr3_discoveries map', '',
       'Mirror of https://github.com/femga/rdr3_discoveries (game data for RDR2/RedM), generated by `tools/map_discoveries.py`.',
       '',
       '## How to use (for AI)',
       '- Find the folder below, then **search** the file. Never read files over ~200KB whole: grep/rg for the name or hash you need.',
       '  e.g. `rg -i "a_c_horse_arabian" data/rdr3_discoveries/peds` or `rg -i "WORLD_HUMAN_SMOKE" data/rdr3_discoveries/animations`',
       '- The sample column shows the line format, so you know what pattern to search for.',
       '- Cite the file a value came from. If something isn\'t here, say so rather than guessing.',
       '- Prefer native names over raw hashes; `discoveredNatives/` has hashes for natives the docs lack.',
       '', '## Folders', '', '| Folder | What\'s in it | Files | Size |', '|---|---|---|---|']
for top in sorted(groups):
    items = groups[top]
    out.append(f'| [{top}](#{top.lower()}) | {HINTS.get(top, "")} | {len(items)} | {human(sum(i[1] for i in items))} |')
for top in sorted(groups):
    out += ['', f'## {top}', '', '| File | Size | Lines | Description | Sample line |', '|---|---|---|---|---|']
    for rel, size, lines, title, sample in groups[top]:
        out.append(f'| `{rel}` | {human(size)} | {lines} | {title} | {"`" + sample + "`" if sample else ""} |')
with open(OUT, 'w', encoding='utf-8') as fh: fh.write('\n'.join(out) + '\n')
print('wrote', OUT, sum(len(v) for v in groups.values()), 'files')
