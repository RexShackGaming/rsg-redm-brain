dofile('shared/character_ammunition_client.lua')
local caps={regular=200,express=200}
local function baseline(revision,regular,phase)
    return {characterId='c',sessionId='s',epoch='e',revision=revision,pools={regular=regular,express=4},phase=phase}
end
local C=WeaponCharacterAmmoClient.New()
assert(C.Begin(baseline(0,8,'restoring'),caps,10))
assert(not C.Prepare(10,{regular=8,express=4},false))
local restore=assert(C.Prepare(10,{regular=8,express=4},true))
assert(restore.kind=='restore')
assert(not C.Prepare(10,{regular=8,express=4},true))
assert(C.Accept(restore.id,{ok=true,value=baseline(0,8,'active')},10))
assert(C.Prepare(10,{regular=8,express=4},true).unchanged)
local shot=assert(C.Prepare(10,{regular=7,express=4},true))
assert(not C.Accept(shot.id+1,{ok=true,value=baseline(1,7,'active')},10))
assert(C.Status().pending,'stale reply must not clear valid work')
assert(not C.Prepare(10,{regular=6,express=4},true))
assert(C.Accept(shot.id,{ok=true,value=baseline(1,7,'active')},10))
local second=assert(C.Prepare(10,{regular=6,express=4},true))
assert(second.expected.revision==2,'shots during save remain available to next sample')
assert(C.Accept(second.id,{ok=true,value=baseline(2,6,'active')},10))
assert(not C.Prepare(11,{regular=0,express=0},true))
assert(C.Status().phase=='suspended','new ped zero must never become consumption')
C.Close(); assert(C.Begin(baseline(2,6,'restoring'),caps,11))
local newer=assert(C.Prepare(11,{regular=6,express=4},true))
assert(newer.id>second.id)
assert(not C.Accept(second.id,{ok=true,value=baseline(2,6,'active')},11))
assert(C.Accept(newer.id,{ok=true,value=baseline(2,6,'active')},11))
assert(not C.Prepare(11,{regular=7,express=4},true)); assert(C.Status().phase=='frozen')
C.Close(); assert(C.Begin(baseline(2,6,'restoring'),caps,11))
assert(not C.Prepare(11,{regular=0,express=0},true)); assert(C.Status().phase=='frozen')
C.Close(); assert(C.Begin(baseline(2,6,'restoring'),caps,11))
local req=assert(C.Prepare(11,{regular=6,express=4},true))
assert(not C.Accept(req.id,{ok=true,value=baseline(2,5,'active')},11)); assert(C.Status().phase=='frozen')
