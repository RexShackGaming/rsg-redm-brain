dofile('shared/character_ammunition_runtime.lua')
dofile('shared/character_ammunition_client.lua')
local current=true
local R=WeaponCharacterAmmoRuntime.New(function() return current end)
local C=WeaponCharacterAmmoClient.New()
local limits={regular=200,express=200}
local context={source=1,characterId='c',sessionId='s'}
local opened=assert(R.Open(context,{characterId='c',revision=0,pools={regular=8,express=4}},limits,'epoch'))
assert(C.Begin(opened,limits,10))
local request=assert(C.Prepare(10,{regular=8,express=4},true))
assert(C.Accept(request.id,{ok=true,value=assert(R.ConfirmRestore(1,request.report))},10))
local final=assert(C.PrepareFinal(10,{regular=7,express=4},true))
local operation=assert(R.PrepareFinalObservation(1,final.report))
assert(not R.Open(context,{characterId='c',revision=0,pools={regular=8,express=4}},limits,'new'),'no reset during final SQL')
assert(not R.PrepareObservation(1,final.report))
assert(not C.Prepare(10,{regular=7,express=4},true))
local sealed=assert(R.Complete(operation.context,{ok=true,value={characterId='c',revision=1,pools=operation.spec.pools}}))
assert(sealed.phase=='sealed' and sealed.pools.regular==7)
assert(C.Accept(final.id,{ok=true,value=sealed},10).phase=='sealed')
assert(not C.Prepare(10,{regular=0,express=0},true),'zero after reset cannot be consumption')
assert(not R.PrepareObservation(1,final.report))
local reopened=assert(R.Open(context,{characterId='c',revision=1,pools=sealed.pools},limits,'new'))
C.Close(); assert(C.Begin(reopened,limits,11))
request=assert(C.Prepare(11,sealed.pools,true))
assert(not C.Accept(final.id,{ok=true,value=sealed},11),'old epoch reply cannot match new work')
assert(C.Accept(request.id,{ok=true,value=assert(R.ConfirmRestore(1,request.report))},11))
final=assert(C.PrepareFinal(11,sealed.pools,true))
local idle=assert(R.PrepareFinalObservation(1,final.report))
assert(idle.unchanged and idle.value.phase=='sealed','idle final ack seals with no DB operation')
assert(C.Accept(final.id,{ok=true,value=idle.value},11))
-- A failed final write freezes instead of permitting reset to an older durable total.
opened=assert(R.Open(context,{characterId='c',revision=1,pools=sealed.pools},limits,'failure'))
local report={characterId='c',sessionId='s',epoch='failure',revision=1,pools=sealed.pools}
assert(R.ConfirmRestore(1,report)); report.pools={regular=6,express=4}
operation=assert(R.PrepareFinalObservation(1,report))
assert(not R.Complete(operation.context,{ok=false}))
assert(R.Get(1).phase=='frozen')
assert(not R.Open(context,{characterId='c',revision=1,pools=sealed.pools},limits,'unsafe'))
print('character_ammunition_reset_spec PASS')
